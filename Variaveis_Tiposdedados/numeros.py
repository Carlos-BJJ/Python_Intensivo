#Inteiros

print(2 + 3)
print(2 - 3)
print(2 * 3)
print(2 / 3) #A divisão de inteiros, resulta em float

#Floats

print(2.1 + 3.2)
print(2.1 - 3.2)
print(2.1 * 3.2)
print(2.1 / 3.2)
#OBS.: Caso faça uma operação entre int e float, resultará em float

